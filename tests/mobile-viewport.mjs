import assert from 'node:assert/strict';
import {visibleViewportHeight,observeViewport,supportsFullscreen,simulatedSafeArea} from '../app/mobile-viewport.mjs';
let checks=0;const check=(value,label)=>{assert.ok(value,label);checks++;};
check(visibleViewportHeight(844,724.9)===724,'use the visible browser area');
check(visibleViewportHeight(724,844)===724,'visual metrics cannot enlarge the layout viewport');
check(visibleViewportHeight(844,undefined)===844,'fallback without VisualViewport');
check(visibleViewportHeight(844,0)===844,'ignore transient zero heights');
check(visibleViewportHeight(844,360,2,724)===724,'pinch magnifies without rebuilding the instrument');
check(visibleViewportHeight(844,360,2)===844,'restored pinch zoom also retains the layout at first mount');
check(visibleViewportHeight(0,0,1,724)===724,'background zero metrics do not collapse the stage');
check(supportsFullscreen({fullscreenEnabled:true,documentElement:{requestFullscreen(){}}}),'standard fullscreen feature detection');
check(!supportsFullscreen({fullscreenEnabled:false,documentElement:{requestFullscreen(){}}}),'do not show a disabled fullscreen action');
check(!supportsFullscreen({documentElement:{}}),'iPhone without element fullscreen remains usable');
check(JSON.stringify(simulatedSafeArea('44,44,21'))==='{"left":44,"right":44,"bottom":21}','legacy safe-area regression URLs remain valid');
check(JSON.stringify(simulatedSafeArea('47,0,0,34'))==='{"top":47,"left":0,"right":0,"bottom":34}','portrait notch and home-indicator simulation');
for(const invalid of [null,'44,21','100,0,0,0','0,0,0,0,0','0px,0,0','0;display:none,0,0'])check(Object.keys(simulatedSafeArea(invalid)).length===0,'invalid safe-area inputs never alter CSS');

const events=()=>({listeners:new Map(),addEventListener(type,fn){this.listeners.set(type,fn);},removeEventListener(type,fn){if(this.listeners.get(type)===fn)this.listeners.delete(type);}});
const win=Object.assign(events(),{innerHeight:844,visualViewport:Object.assign(events(),{height:724,scale:1})});
let nextFrame=1;const frames=new Map(),writes=[];
win.requestAnimationFrame=fn=>{const id=nextFrame++;frames.set(id,fn);return id;};win.cancelAnimationFrame=id=>frames.delete(id);
const flush=()=>{const pending=[...frames.values()];frames.clear();pending.forEach(fn=>fn());};
const cleanup=observeViewport(win,{style:{setProperty(...args){writes.push(args);}}});
check(writes.length===1&&writes[0][1]==='724px','initial visible height is applied');
win.visualViewport.height=744;
win.listeners.get('resize')();win.visualViewport.listeners.get('resize')();win.listeners.get('orientationchange')();
check(frames.size===1,'coalesce browser resize storms into one frame');flush();
check(writes.length===2&&writes[1][1]==='744px','toolbar change updates once');
win.listeners.get('resize')();flush();check(writes.length===2,'unchanged metrics do not write layout styles');
win.visualViewport.scale=2;win.visualViewport.height=372;win.visualViewport.listeners.get('resize')();flush();
check(writes.length===2,'pinch does not recursively shrink the scene');
win.visualViewport.scale=1;win.innerHeight=390;win.visualViewport.height=320;win.listeners.get('orientationchange')();flush();
check(writes.at(-1)[1]==='320px','orientation uses fresh available height');
win.listeners.get('pageshow')();cleanup();
check(!frames.size&&!win.listeners.size&&!win.visualViewport.listeners.size,'cleanup cancels queued work and all listeners');
console.log(`${checks} mobile browser viewport and fullscreen checks passed`);
